import json
from pathlib import Path

from src.key_management import generate_key_pair
from src.encryption import encrypt_file
from src.decryption import decrypt_file


# ==========================================================
# HELPER FUNCTIONS
# ==========================================================

def title(text):
    print("\n" + "=" * 58)
    print(f" {text}")
    print("=" * 58)


def pause():
    input("\nPress ENTER to continue...")


def check(condition, message):
    if not condition:
        raise RuntimeError(f"[FAIL] {message}")

    print(f"[PASS] {message}")


def show_container(path):
    """Display a summary of the encrypted .vault container."""

    with path.open("r", encoding="utf-8") as file:
        container = json.load(file)

    print("\nENCRYPTED CONTAINER (.vault)")
    print("-" * 40)

    metadata = container.get("metadata", {})
    recipients = container.get("recipients", [])

    print(f"File name: {metadata.get('filename', 'Unknown')}")
    print(f"Algorithm: {metadata.get('algorithm', 'Unknown')}")
    print(f"Key encryption: {metadata.get('key_encryption', 'Unknown')}")
    print(f"Authorized recipients: {len(recipients)}")

    print("\nContainer structure:")
    print("  metadata")
    print("  recipients")
    print("  nonce")
    print("  ciphertext")

    print("\nRecipient identifiers:")

    for index, recipient in enumerate(recipients, start=1):
        fingerprint = recipient.get("id", "Unknown")
        print(f"  Recipient {index}: {fingerprint[:16]}...")

    print("\nThe original document and private keys")
    print("are NOT stored inside the container.")


def clean_demo_files(folder):
    """Remove files generated by previous demonstrations."""

    demo_filenames = [
        "confidential_document.txt",
        "confidential_document.vault",
        "alice_decrypted.txt",
        "bob_decrypted.txt",
        "charlie_decrypted.txt",
        "modified_document.vault",
        "tampered_decrypted.txt",
    ]

    for filename in demo_filenames:
        file_path = folder / filename

        if file_path.is_file():
            file_path.unlink()


# ==========================================================
# MAIN DEMONSTRATION
# ==========================================================

def main():

    title("SECURE DIGITAL DOCUMENT VAULT")

    print("D3 - LIVE DEMONSTRATION")
    print("AES-256-GCM + ECIES")

    print("\nAuthorized users: Alice and Bob")
    print("Unauthorized user: Charlie")

    # ------------------------------------------------------
    # CREATE DEMONSTRATION FOLDER
    # ------------------------------------------------------

    folder = Path(__file__).resolve().parent / "demo_files"
    folder.mkdir(exist_ok=True)

    # Remove files from previous demonstrations.
    clean_demo_files(folder)

    print("\nDemo folder:")
    print(folder)

    # ------------------------------------------------------
    # GENERATE USER KEYS
    # ------------------------------------------------------

    print("\nGenerating cryptographic keys...")

    alice_private, alice_public = generate_key_pair()
    bob_private, bob_public = generate_key_pair()
    charlie_private, _ = generate_key_pair()

    print("[PASS] Keys generated for Alice, Bob, and Charlie.")

    # ------------------------------------------------------
    # CREATE ORIGINAL DOCUMENT
    # ------------------------------------------------------

    original = folder / "confidential_document.txt"
    encrypted = folder / "confidential_document.vault"

    original.write_text(
        "This is a confidential document.\n"
        "Only Alice and Bob are authorized to read it.\n",
        encoding="utf-8",
    )

    original_content = original.read_bytes()

    print("\nOriginal document created:")
    print(original.name)

    # ======================================================
    # SCENARIO 1: ENCRYPTION AND DECRYPTION
    # ======================================================

    title("SCENARIO 1: ENCRYPTION & DECRYPTION")

    print("\nAlice creates a confidential document.")
    print("The system encrypts it using AES-256-GCM.")

    encrypt_file(
        original,
        encrypted,
        [alice_public, bob_public],
    )

    check(
        encrypted.is_file(),
        "Encrypted document created successfully.",
    )

    # Display the encrypted container information.
    show_container(encrypted)

    # Alice decrypts the document.
    alice_output = folder / "alice_decrypted.txt"

    alice_result = decrypt_file(
        encrypted,
        alice_private,
        alice_output,
    )

    check(
        alice_result is True
        and alice_output.is_file()
        and alice_output.read_bytes() == original_content,
        "Alice recovered the original document.",
    )

    pause()

    # ======================================================
    # SCENARIO 2: AUTHORIZED SHARING
    # ======================================================

    title("SCENARIO 2: AUTHORIZED SHARING")

    print("\nBob receives the same encrypted document.")
    print("He uses his own private key to decrypt it.")

    bob_output = folder / "bob_decrypted.txt"

    bob_result = decrypt_file(
        encrypted,
        bob_private,
        bob_output,
    )

    check(
        bob_result is True
        and bob_output.is_file()
        and bob_output.read_bytes() == original_content,
        "Bob successfully decrypted the shared document.",
    )

    pause()

    # ======================================================
    # SCENARIO 3: UNAUTHORIZED ACCESS
    # ======================================================

    title("SCENARIO 3: UNAUTHORIZED ACCESS")

    print("\nCharlie tries to decrypt the document.")
    print("However, Charlie is not an authorized recipient.")

    charlie_output = folder / "charlie_decrypted.txt"

    charlie_result = decrypt_file(
        encrypted,
        charlie_private,
        charlie_output,
    )

    check(
        charlie_result is False
        and not charlie_output.exists(),
        "ACCESS DENIED: Charlie cannot read the document.",
    )

    pause()

    # ======================================================
    # SCENARIO 4: FILE INTEGRITY
    # ======================================================

    title("SCENARIO 4: FILE INTEGRITY")

    print("\nAn attacker modifies the encrypted document.")
    print("Alice tries to decrypt the modified version.")

    tampered = folder / "modified_document.vault"

    # Read the original encrypted container.
    with encrypted.open("r", encoding="utf-8") as file:
        container = json.load(file)

    # Modify the ciphertext without breaking JSON formatting.
    ciphertext = container["ciphertext"]

    check(
        bool(ciphertext),
        "Encrypted content is available.",
    )

    replacement = "0" if ciphertext[0] != "0" else "1"

    container["ciphertext"] = (
        replacement + ciphertext[1:]
    )

    # Save the modified container as a separate file.
    with tampered.open("w", encoding="utf-8") as file:
        json.dump(container, file, indent=2)

    tampered_output = folder / "tampered_decrypted.txt"

    tampered_result = decrypt_file(
        tampered,
        alice_private,
        tampered_output,
    )

    check(
        tampered_result is False
        and not tampered_output.exists(),
        "INTEGRITY VERIFIED: Modified data was rejected.",
    )

    # ======================================================
    # FINAL RESULTS
    # ======================================================

    title("DEMONSTRATION COMPLETED")

    print("\n[PASS] Encryption and decryption")
    print("[PASS] Authorized sharing")
    print("[PASS] Unauthorized access rejected")
    print("[PASS] Modified document rejected")

    print("\nALL 4 SECURITY SCENARIOS PASSED")

    print("\nDemo files saved in:")
    print(folder)


if __name__ == "__main__":
    main()